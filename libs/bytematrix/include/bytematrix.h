#ifndef BYTEMATRIX_H
#define BYTEMATRIX_H

#include <cstdint>
#include <memory>
#include <string_view>
#include <vector>

namespace bytematrix {

    std::string_view version() noexcept;

    inline constexpr std::size_t kInputBufferCapacity = 100;

    using ByteArray = std::vector<std::uint8_t>;

    class IModule
    {
    public:
        IModule() = default;
        virtual ~IModule() = default;

        // Wires the module that receives this module's output.
        virtual void setNext(IModule* next) = 0;

        // Starts the internal worker thread. Idempotent.
        virtual void start() = 0;

        /*
        Stops the worker, draining what is still buffered. Idempotent, and
        called by the destructor of each module.
        If the worker is parked in the successor's submit(), stop() returns
        once that successor makes room: a running successor drains, a stopped
        one answers false at once. Stopping the source first therefore loses
        nothing in flight; stopping the sink first is faster but drops what
        the middle modules still buffer.
        */
        virtual void stop() = 0;

        /*
        Delivers one payload. Blocks while the input buffer is full
        (backpressure) and returns false when the module is stopped.
        */
        virtual bool submit(ByteArray data) = 0;

    private:
        virtual void run() = 0;
    };

    /*
    Module 1: will generate byte arrays of random length [1...100] containing
    random bytes [0...255]. The byte arrays are generated continuously and
    delivered to the second module.
    */
    [[nodiscard]] std::unique_ptr<IModule> createGenerator();

    /*
    Module 2: The second module will receive the generated byte arrays from the first one
    and will look for a match of `sequence` into the byte array. If a match is found in the
    array, it will deliver the array to the third module, otherwise it will just discard it.
    The module will be able to receive up to 100 byte arrays from the first module
    using an input buffer.

    `sequence` is required: an empty one throws std::invalid_argument, so the mistake is
    reported where the filter is built instead of inside its worker thread.
    */
    [[nodiscard]] std::unique_ptr<IModule> createFilter(ByteArray sequence);

    /*
    Module 3: will receive the byte arrays from the second one and record
    them. Each time a byte array is received, the module will print to the standard
    output ALL the records received to that moment ordered by UTC time. The
    module will be able to receive up to 100 byte arrays from the second module
    using an input buffer.
    */
    [[nodiscard]] std::unique_ptr<IModule> createRecorder();
}

#endif // BYTEMATRIX_H
